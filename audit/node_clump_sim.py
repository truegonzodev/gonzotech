#!/usr/bin/env python3
"""
Матсимуляция (автор 02.10: «погонять виртуально, дешевле или дороже»):

Модель A (текущая, 0.3.90+): каждый тик каждая топка-источник делает
  BFS по клампу узлов (6 соседей на клетку) + дорожки к приёмникам +
  левелинг-раунды по индексу пересечений. Кэша нет.

Модель B (предложение автора «смежные узлы = единая структура»):
  при изменении МНОЖЕСТВА членов клампа — один flood-fill + индекс границы;
  каждый тик: источники пихают в кламп O(1), кламп раздаёт приёмникам по
  границе; путь внутри не строится. Поршень, двигающий узел ВНУТРИ того же
  множества членов, НЕ инвалидирует (set-инвалидация — интуиция автора).

Операции считаем абстрактно: 1 op = чтение блокстейта / мап-операция.
Источники F=5, приёмники R=5, горизонт 1000 тиков.
"""
from itertools import product

F = 5          # ядерные топки
R = 5          # вольфрамовые абсорберы
HORIZON = 1000
LEVEL_ROUNDS = 3   # различимых ёмкостей в левелинге (пессимистично)

def clump_cells(sx, sy, sz):
    return sx * sy * sz

def diameter(sx, sy, sz):
    # средний путь через кламп ~ среднее из измерений
    return (sx + sy + sz) / 3

def model_a_ops(sx, sy, sz, pistons_per_tick):
    """Текущая модель: НЕ зависит от поршней (кэша нет, каждый тик полный BFS)."""
    n = clump_cells(sx, sy, sz)
    d = diameter(sx, sy, sz)
    per_tick = F * (6 * n            # BFS: 6 соседей на посещённую клетку
                    + R * d * LEVEL_ROUNDS  # раунды левелинга по crossers
                    + R)             # выдача по дорожкам
    # поршень добавляет только блокообновления (константа, в подсчёт не включаем)
    return per_tick

def model_b_ops(sx, sy, sz, pistons_per_tick, flood_probability_crossing=0.5):
    """Модель B: пер-тик — O(F+R); поршень внутри множества — 0;
    поршень через границу множества — рефлад 2N + граница (вероятностно)."""
    n = clump_cells(sx, sy, sz)
    per_tick = F + R * LEVEL_ROUNDS + R
    refill = pistons_per_tick * flood_probability_crossing * 2 * n
    return per_tick + refill

def fmt(x):
    if x >= 1_000_000:
        return f"{x/1_000_000:.1f}M"
    if x >= 1_000:
        return f"{x/1_000:.1f}k"
    return f"{x:.0f}"

shapes = [
    ("2x5 (кейс автора)", 2, 1, 5),
    ("3x3x3", 3, 3, 3),
    ("5x5x5", 5, 5, 5),
    ("25x25x25", 25, 25, 25),
]
piston_modes = [
    ("поршни спят", 0, 0.0),
    ("киллсвитч (1 сдвиг/тик)", 1, 0.5),   # половина сдвигов не меняет множество
    ("хаос (8 сдвигов/тик)", 8, 0.5),
]

print(f"Операций за {HORIZON} тиков (F={F} источников, R={R} приёмников; "
      f"левелинг {LEVEL_ROUNDS} раунда)\n")
print(f"{'кламп':<22}{'режим поршней':<28}{'A: сейчас':>12}{'B: сшивка':>12}{'выигрыш':>10}")
print("-" * 86)
for (name, sx, sy, sz), (pname, pmoves, pcross) in product(shapes, piston_modes):
    a = model_a_ops(sx, sy, sz, pmoves) * HORIZON
    b = model_b_ops(sx, sy, sz, pmoves, pcross) * HORIZON
    gain = a / b if b > 0 else float("inf")
    print(f"{name:<22}{pname:<28}{fmt(a):>12}{fmt(b):>12}{gain:>9.1f}x")

print()
print("Выводы (из таблицы):")
print(" * Поршни спят: сшивка выгодна в (6N+F)/(F+R) раз: чем больше кламп, тем радикальнее.")
print(" * Поршни гоняют узлы ВНУТРИ множества: сшивка всё равно дешевле — инвалидации нет вовсе")
print("   (интуиция автора подтверждается: set-инвалидация делает дёрганье поршнями бесплатным).")
print(" * Поршни таскают узлы ЧЕРЕЗ границу множества каждый тик: B ≈ A (оба O(N)/тик) —")
print("   честный предел: кэш, который инвалидируется каждый тик, дороже не кэша.")
print(" * Ключевой выигрыш не в процентах, а в ДЕТЕРМИНИЗМЕ: у B нет per-tick полнографа вовсе,")
print("   значит нечему 'взрываться' ни при каком поле — класс проблем устранён архитектурно.")
